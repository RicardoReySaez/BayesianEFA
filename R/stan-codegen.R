# stan-codegen.R
# Build the Stan code of a BEFA model from its structure
# Author: Ricardo Rey-Sáez
# Last modified: 11-11-2026

# Every density keeps its additive constants, so the log density that Stan
# reports is the full log posterior (up to the Jacobian of the constrained
# parameters, which Stan adds itself), or the full log prior when the data
# set `prior_only` to 1. The code only uses features of Stan 2.32, the
# version rstan ships.

# Internal functions

# This function returns the Stan code of a model structure (see .befa_spec()).
# The code depends on the structure alone, never on the data, so models with
# the same structure share one compiled program, also when they sample the
# prior alone. Each component adds lines to the blocks of the program, which
# are assembled in a fixed order.
.stan_code <- function(spec) {
  parts <- list(.stan_dims(spec), .stan_loadings(spec), .stan_scale(spec),
                .stan_means(spec),
                .stan_likelihood_switch(.stan_likelihood(spec)))
  block <- function(name) {
    lines <- unlist(lapply(parts, `[[`, name))
    if (!length(lines)) return(NULL)
    title <- gsub("_", " ", name)
    c(paste(title, "{"), paste0("  ", lines), "}")
  }
  code <- c(
    paste0("// Generated by BayesianEFA (", .spec_label(spec), "). ",
           "Do not edit by hand."),
    block("functions"), block("data"), block("transformed_data"),
    block("parameters"), block("model")
  )
  paste0(paste(code, collapse = "\n"), "\n")
}

# This function writes a declaration with its comment aligned in one column,
# so the data block of the generated code reads as a table.
.stan_decl <- function(code, comment) {
  sprintf("%-38s // %s", code, comment)
}

# This function returns the dimensions and the summaries of the observations.
# A single pattern reads the root of the scatter matrix of all rows (S_root,
# with S_root * S_root' = sum of y y', around the means in the raw model). With
# several patterns, the observed items, the roots and the means of every
# pattern are stacked one after another.
.stan_dims <- function(spec) {
  raw <- spec$model_type == "raw"
  # The null model and the Woodbury engine with one pattern read the squared
  # norms of the rows of the scatter roots, which are data.
  norms <- spec$loadings == "none" ||
    (spec$engine == "woodbury" && spec$patterns == "single")
  M <- switch(spec$loadings,
              uv = .stan_decl("int<lower=2> M;", "factors"),
              normal = .stan_decl("int<lower=1> M;", "factors"))
  dims <- c(.stan_decl("int<lower=1> N;", "rows"),
            .stan_decl("int<lower=1> J;", "items"),
            M)
  if (spec$patterns == "single") {
    data <- c(
      dims,
      .stan_decl("int<lower=1> K;", "columns of the scatter root"),
      .stan_decl("matrix[J, K] S_root;", "S_root * S_root' = scatter matrix"),
      if (raw) .stan_decl("vector[J] y_bar;", "item means")
    )
    tdata <- c(
      "real ll_const = -0.5 * N * J * log(2 * pi());",
      if (norms) "vector[J] root_r2 = rows_dot_self(S_root);"
    )
    return(list(data = data, transformed_data = tdata))
  }

  data <- c(
    dims,
    .stan_decl("int<lower=1> P;", "patterns of observed items"),
    .stan_decl("array[P] int<lower=1> n_p;", "rows per pattern"),
    .stan_decl("array[P] int<lower=1, upper=J> J_p;", "observed items per pattern"),
    .stan_decl("array[P] int<lower=1> K_p;", "columns of each scatter root"),
    .stan_decl("array[sum(J_p)] int<lower=1, upper=J> obs_idx;",
               "observed items, stacked"),
    .stan_decl("int<lower=1> n_root;", "length of root_flat"),
    .stan_decl("vector[n_root] root_flat;", "scatter roots, stacked"),
    if (raw) .stan_decl("vector[sum(J_p)] ybar_flat;", "pattern means, stacked")
  )
  tdata <- c(
    "real ll_const;",
    if (norms) "vector[sum(J_p)] root_r2;",
    "{",
    "  int n_cells = 0;",
    "  int n_check = 0;",
    "  for (p in 1:P) {",
    "    n_cells += n_p[p] * J_p[p];",
    "    n_check += J_p[p] * K_p[p];",
    "  }",
    "  if (n_check != n_root) {",
    "    reject(\"root_flat has \", n_root, \" values; the patterns need \", n_check, \".\");",
    "  }",
    "  ll_const = -0.5 * n_cells * log(2 * pi());",
    "}",
    if (norms) c(
      "{",
      "  int pos_j = 1;",
      "  int pos_r = 1;",
      "  for (p in 1:P) {",
      "    root_r2[pos_j:(pos_j + J_p[p] - 1)] = rows_dot_self(",
      "      to_matrix(segment(root_flat, pos_r, J_p[p] * K_p[p]), J_p[p], K_p[p]));",
      "    pos_j += J_p[p];",
      "    pos_r += J_p[p] * K_p[p];",
      "  }",
      "}"
    )
  )
  list(data = data, transformed_data = tdata)
}

# This function returns the loadings, their prior and the expressions of the
# standardized structure they imply: the whole matrix (`structure`), and its
# factor part (`factor`, with `rank` columns) and uniquenesses (`unique`) for
# the Woodbury engine. Unit-vector loadings are sqrt(h2) times
# the direction of each row of Z, whose density
# ||z||^xi exp(-||z||^2 / 2) keeps the norm away from zero; its normalizing
# constant per row is log_C, as ||z||^2 follows a chi-squared distribution
# with xi + M degrees of freedom and the direction is uniform. One factor
# under the unit-vector prior uses a Beta prior scaled to (-1, 1), and the
# normal prior places independent normal priors on the loadings in the metric
# of the items, with inverse-gamma uniquenesses.
.stan_loadings <- function(spec) {
  switch(spec$loadings,
    uv = list(
      data = c(.stan_decl("vector<lower=0>[2] pr_h2;", "Beta prior on h2"),
               .stan_decl("real<lower=0> pr_xi;", "repulsion of the norms of Z")),
      transformed_data = c(
        "real log_C = 0.5 * M * log(pi()) + 0.5 * (pr_xi + M) * log2()",
        "             + lgamma(0.5 * (pr_xi + M)) - lgamma(0.5 * M);"
      ),
      parameters = c("vector<lower=0, upper=1>[J] h2;",
                     "matrix[J, M] Z;"),
      model = c(
        "vector[J] r2 = rows_dot_self(Z);",
        "matrix[J, M] Lambda_std = diag_pre_multiply(sqrt(h2 ./ r2), Z);",
        "target += beta_lpdf(h2 | pr_h2[1], pr_h2[2]);",
        "target += 0.5 * pr_xi * sum(log(r2)) - 0.5 * sum(r2) - J * log_C;"
      ),
      structure = "add_diag(tcrossprod(Lambda_std), 1 - h2)",
      factor = "Lambda_std", unique = "1 - h2", rank = "M"
    ),
    uni = list(
      functions = c(
        "// Beta(alpha, beta) density moved from (0, 1) to (-1, 1)",
        "real scaled_beta_lpdf(vector y, real alpha, real beta) {",
        "  int K = num_elements(y);",
        "  return sum((alpha - 1) * log1p(y) + (beta - 1) * log1m(y))",
        "         - K * (alpha + beta - 1) * log(2) - K * lbeta(alpha, beta);",
        "}"
      ),
      data = .stan_decl("vector<lower=0>[2] pr_lambda;",
                        "scaled Beta prior on the loadings"),
      parameters = "vector<lower=-1, upper=1>[J] lambda_std;",
      model = "target += scaled_beta_lpdf(lambda_std | pr_lambda[1], pr_lambda[2]);",
      structure = "add_diag(lambda_std * lambda_std', 1 - square(lambda_std))",
      factor = "lambda_std", unique = "1 - square(lambda_std)", rank = "1"
    ),
    normal = list(
      data = c(.stan_decl("vector[J] pr_lambda_loc;", "normal prior on the loadings"),
               .stan_decl("vector<lower=0>[J] pr_lambda_scale;", "its scale per item"),
               .stan_decl("real<lower=0> pr_psi_shape;", "inverse-gamma prior on psi"),
               .stan_decl("vector<lower=0>[J] pr_psi_scale;", "its scale per item")),
      parameters = c("matrix[J, M] Lambda;",
                     "vector<lower=0>[J] psi;"),
      model = c(
        "for (m in 1:M) {",
        "  target += normal_lpdf(col(Lambda, m) | pr_lambda_loc, pr_lambda_scale);",
        "}",
        "target += inv_gamma_lpdf(psi | pr_psi_shape, pr_psi_scale);"
      ),
      structure = "add_diag(tcrossprod(Lambda), psi)",
      factor = "Lambda", unique = "psi", rank = "M"
    ),
    none = list()
  )
}

# This function returns the item standard deviations that scale a
# standardized structure, with a half-Student-t prior whose truncation at zero
# is part of the density.
.stan_scale <- function(spec) {
  if (!.spec_has_scale(spec)) return(list())
  list(
    data = .stan_decl("vector<lower=0>[3] pr_sigma;", "half-t(df, location, scale)"),
    parameters = "vector<lower=0>[J] sigma;",
    model = c(
      "target += student_t_lpdf(sigma | pr_sigma[1], pr_sigma[2], pr_sigma[3])",
      "          - J * student_t_lccdf(0 | pr_sigma[1], pr_sigma[2], pr_sigma[3]);"
    )
  )
}

# This function returns the item means of the raw model and their prior.
.stan_means <- function(spec) {
  if (spec$model_type != "raw") return(list())
  list(
    data = .stan_decl("vector[2] pr_nu;", "normal prior on the means"),
    parameters = "vector[J] nu;",
    model = "target += normal_lpdf(nu | pr_nu[1], pr_nu[2]);"
  )
}

# This function lets the data leave the log-likelihood out: the model block
# adds it only when `prior_only` is 0, so with 1 the same program samples the
# prior. What the likelihood computes in the transformed data is kept.
.stan_likelihood_switch <- function(likelihood) {
  likelihood$data <- .stan_decl("int<lower=0, upper=1> prior_only;",
                                "1 leaves the likelihood out")
  likelihood$model <- c("if (!prior_only) {", paste0("  ", likelihood$model),
                        "}")
  likelihood
}

# This function returns the log-likelihood. For each pattern p, with n_p
# rows, the scatter root R_p and the pattern means,
#   -1/2 [n_p J_p log(2 pi) + n_p log|Sigma_p| + ||L_p^-1 R_p||^2
#         + n_p ||L_p^-1 (y_bar_p - nu_p)||^2],
# where L_p is the Cholesky factor of Sigma_p, so one decomposition gives both
# the determinant and the quadratic forms. The null model has a diagonal
# Sigma and needs no decomposition, and the Woodbury engine avoids the J x J
# matrix (see .stan_likelihood_woodbury()).
.stan_likelihood <- function(spec) {
  if (spec$loadings == "none") return(.stan_likelihood_diagonal(spec))
  if (spec$engine == "woodbury") return(.stan_likelihood_woodbury(spec))
  raw <- spec$model_type == "raw"
  sigma <- .stan_loadings(spec)$structure
  if (.spec_has_scale(spec)) sigma <- paste0("quad_form_diag(", sigma, ", sigma)")
  model <- paste0("matrix[J, J] Sigma = ", sigma, ";")

  if (spec$patterns == "single") {
    model <- c(
      model,
      "matrix[J, J] L = cholesky_decompose(Sigma);",
      "target += ll_const - N * sum(log(diagonal(L)))",
      "          - 0.5 * sum(square(mdivide_left_tri_low(L, S_root)));",
      if (raw) "target += -0.5 * N * dot_self(mdivide_left_tri_low(L, y_bar - nu));"
    )
    return(list(model = model))
  }

  model <- c(
    model,
    "target += ll_const;",
    "{",
    "  int pos_j = 1;",
    "  int pos_r = 1;",
    "  for (p in 1:P) {",
    "    array[J_p[p]] int idx = segment(obs_idx, pos_j, J_p[p]);",
    "    matrix[J_p[p], J_p[p]] L_p = cholesky_decompose(Sigma[idx, idx]);",
    "    matrix[J_p[p], K_p[p]] R_p",
    "      = to_matrix(segment(root_flat, pos_r, J_p[p] * K_p[p]), J_p[p], K_p[p]);",
    "    target += -n_p[p] * sum(log(diagonal(L_p)))",
    "              - 0.5 * sum(square(mdivide_left_tri_low(L_p, R_p)));",
    if (raw) c(
      "    target += -0.5 * n_p[p] * dot_self(mdivide_left_tri_low(",
      "      L_p, segment(ybar_flat, pos_j, J_p[p]) - nu[idx]));"
    ),
    "    pos_j += J_p[p];",
    "    pos_r += J_p[p] * K_p[p];",
    "  }",
    "}"
  )
  list(model = model)
}

# This function returns the log-likelihood with the Woodbury identity. With
# Sigma = A A' + U, U = diag(u) and the capacitance matrix
# C = I + A' U^-1 A = L_C L_C' (M x M), each pattern needs
#   log|Sigma_p| = sum(log(u_p)) + 2 sum(log(diag(L_C)))
#   tr(Sigma_p^-1 R_p R_p') = sum(root_r2_p ./ u_p) - ||L_C^-1 W_p' R_p||^2,
# with W = U^-1 A, so the cost grows with J M instead of J^3 and no J x J
# matrix is formed. The mean term of the raw model follows the same way.
.stan_likelihood_woodbury <- function(spec) {
  raw <- spec$model_type == "raw"
  parts <- .stan_loadings(spec)
  R <- parts$rank
  A <- parts$factor
  u <- parts$unique
  if (.spec_has_scale(spec)) {
    A <- if (R == "1") paste0("sigma .* ", A) else paste0("diag_pre_multiply(sigma, ", A, ")")
    u <- paste0("square(sigma) .* (", u, ")")
  }
  if (R == "1") A <- paste0("to_matrix(", A, ")")
  model <- c(
    sprintf("matrix[J, %s] A = %s;", R, A),
    sprintf("vector[J] inv_u = inv(%s);", u),
    sprintf("matrix[J, %s] B = diag_pre_multiply(sqrt(inv_u), A);", R),
    sprintf("matrix[J, %s] W = diag_pre_multiply(inv_u, A);", R)
  )

  if (spec$patterns == "single") {
    model <- c(
      model,
      sprintf("matrix[%s, %s] L_C = cholesky_decompose(add_diag(crossprod(B), 1));", R, R),
      "target += ll_const + 0.5 * N * sum(log(inv_u)) - N * sum(log(diagonal(L_C)))",
      "          - 0.5 * (dot_product(root_r2, inv_u)",
      "                   - sum(square(mdivide_left_tri_low(L_C, W' * S_root))));",
      if (raw) c(
        "target += -0.5 * N * (dot_product(square(y_bar - nu), inv_u)",
        "                      - dot_self(mdivide_left_tri_low(L_C, W' * (y_bar - nu))));"
      )
    )
    return(list(model = model))
  }

  # With several patterns, everything that grows with J is computed for all
  # patterns at once: the capacitance matrices from the products of the
  # columns of B (C_flat), the projections W' R_p of every column of the
  # roots (Q), and the terms in u from counts and sums per item. Each pattern
  # then needs only the Cholesky factor of its M x M matrix.
  RR <- if (R == "1") "1" else "M * M"
  model <- c(
    model,
    sprintf("matrix[J, %s] BB;", RR),
    sprintf("for (k in 1:%s) {", R),
    sprintf("  for (l in 1:%s) {", R),
    sprintf("    BB[, (k - 1) * %s + l] = B[, k] .* B[, l];", R),
    "  }",
    "}",
    sprintf("matrix[P, %s] C_flat = obs_mat * BB;", RR),
    sprintf("matrix[K_tot, %s] Q = root_pad * W;", R),
    if (raw) c(
      "matrix[P, J] D = ybar_pad - diag_post_multiply(obs_mat, nu);",
      sprintf("matrix[P, %s] Q_d = D * W;", R)
    ),
    "real logdet_C = 0;",
    "real quad_C = 0;",
    if (raw) "real mean_C = 0;",
    "{",
    "  int pos_k = 1;",
    "  for (p in 1:P) {",
    sprintf("    matrix[%s, %s] L_C", R, R),
    sprintf("      = cholesky_decompose(add_diag(to_matrix(C_flat[p], %s, %s), 1));", R, R),
    "    logdet_C += n_p[p] * sum(log(diagonal(L_C)));",
    sprintf("    quad_C += sum(square(mdivide_left_tri_low(L_C, block(Q, pos_k, 1, K_p[p], %s)')));", R),
    if (raw) "    mean_C += n_p[p] * dot_self(mdivide_left_tri_low(L_C, Q_d[p]'));",
    "    pos_k += K_p[p];",
    "  }",
    "}",
    "target += ll_const + 0.5 * dot_product(n_obs, log(inv_u)) - logdet_C",
    "          - 0.5 * (dot_product(r2_item, inv_u) - quad_C);",
    if (raw) {
      "target += -0.5 * (dot_product(to_vector(n_p), (D .* D) * inv_u) - mean_C);"
    }
  )

  tdata <- c(
    "int K_tot = sum(K_p);",
    "matrix[P, J] obs_mat = rep_matrix(0, P, J);",
    "matrix[K_tot, J] root_pad = rep_matrix(0, K_tot, J);",
    "vector[J] n_obs = rep_vector(0, J);",
    if (raw) "matrix[P, J] ybar_pad = rep_matrix(0, P, J);",
    "{",
    "  int pos_j = 1;",
    "  int pos_r = 1;",
    "  int pos_k = 1;",
    "  for (p in 1:P) {",
    "    array[J_p[p]] int idx = segment(obs_idx, pos_j, J_p[p]);",
    "    obs_mat[p, idx] = rep_row_vector(1, J_p[p]);",
    "    n_obs[idx] = n_obs[idx] + n_p[p];",
    "    root_pad[pos_k:(pos_k + K_p[p] - 1), idx]",
    "      = to_matrix(segment(root_flat, pos_r, J_p[p] * K_p[p]), J_p[p], K_p[p])';",
    if (raw) "    ybar_pad[p, idx] = segment(ybar_flat, pos_j, J_p[p])';",
    "    pos_j += J_p[p];",
    "    pos_r += J_p[p] * K_p[p];",
    "    pos_k += K_p[p];",
    "  }",
    "}",
    "vector[J] r2_item = columns_dot_self(root_pad)';"
  )
  list(transformed_data = tdata, model = model)
}

# This function returns the log-likelihood of the null model, whose diagonal
# covariance matrix diag(sigma^2) only needs the squared norms of the rows of
# the scatter roots (root_r2).
.stan_likelihood_diagonal <- function(spec) {
  raw <- spec$model_type == "raw"
  if (spec$patterns == "single") {
    return(list(model = c(
      "target += ll_const - N * sum(log(sigma)) - 0.5 * sum(root_r2 ./ square(sigma));",
      if (raw) "target += -0.5 * N * sum(square((y_bar - nu) ./ sigma));"
    )))
  }
  list(model = c(
    "target += ll_const;",
    "{",
    "  int pos_j = 1;",
    "  for (p in 1:P) {",
    "    array[J_p[p]] int idx = segment(obs_idx, pos_j, J_p[p]);",
    "    target += -n_p[p] * sum(log(sigma[idx]))",
    "              - 0.5 * sum(segment(root_r2, pos_j, J_p[p]) ./ square(sigma[idx]));",
    if (raw) c(
      "    target += -0.5 * n_p[p]",
      "              * sum(square((segment(ybar_flat, pos_j, J_p[p]) - nu[idx]) ./ sigma[idx]));"
    ),
    "    pos_j += J_p[p];",
    "  }",
    "}"
  ))
}
